const assert = require('node:assert/strict');
const { estimate } = require('../dist/energy.js');
const start = Date.parse('2026-11-13T00:00:00Z') / 1000;
const time = Array.from({ length: 27 }, (_, i) => start + (i - 1) * 3600);
const hourly = { time, global_tilted_irradiance: time.map(t => t > start && t <= start + 86400 ? 250 : 1000) };
const result = estimate(hourly, start, start + 86400, 11, 20);
assert.equal(result.irradiation, 6);
assert(Math.abs(result.kwh - 52.8) < 1e-10);
const fractional = { time, global_tilted_irradiance: time.map(() => 100) };
assert(Math.abs(estimate(fractional, start + 900, start + 87300, 1, 0).kwh - 2.4) < 1e-10);
assert.throws(() => estimate({ time: time.slice(0, 10), global_tilted_irradiance: time.map(() => 250) }, start, start + 86400, 11, 20), /đủ dữ liệu/);
const missing = { time, global_tilted_irradiance: time.map(() => null) };
assert.throws(() => estimate(missing, start, start + 86400, 11, 20), /chưa đầy đủ/);
assert.throws(() => estimate(hourly, start, start + 86400, -1, 20));
assert.equal(estimate({ time, global_tilted_irradiance: time.map(() => 0) }, start, start + 86400, 11, 20).kwh, 0);
console.log('Energy checks passed: 11 kWp conversion, day boundaries, fractional offsets, missing data, zero irradiance.');
const energy = require('../dist/energy.js');
const weather = { ...hourly, cloud_cover: time.map(() => 100), rain: time.map(() => 2), showers: time.map(() => 0) };
const reserve = energy.weatherReserve(weather, result);
assert(Math.abs(reserve.percent - 25) < 1e-9);
assert(Math.abs(reserve.kwh - result.kwh * .75) < 1e-9);
assert.equal(energy.weatherReserve({ ...weather, cloud_cover: time.map(() => 0), rain: time.map(() => 0) }, result).percent, 0);
assert.equal(energy.weatherReserve({ ...weather, rain: time.map(() => null) }, result), null);
const night = { hours: [{ time: time[0], kwh: 0 }, { time: time[1], kwh: 10 }], kwh: 10 };
const nightWeather = { time: time.slice(0, 2), cloud_cover: [100, 0], rain: [10, 0], showers: [0, 0] };
assert.equal(energy.weatherReserve(nightWeather, night).kwh, 10);
console.log('Reserve checks passed: cap, clear weather, missing data, no penalty for nighttime rain.');
assert.throws(() => estimate({time:[start+1800,start+3600],global_tilted_irradiance:[500,500]},start,start+3600,11,20), /Mốc thời gian/);
assert.throws(() => estimate(hourly,start,start,11,20), /Mốc thời gian/);
console.log('Energy malformed-interval checks passed.');
