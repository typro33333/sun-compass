import assert from 'node:assert/strict';
import { createForecastProxy } from '../lib/forecast-proxy.mjs';
let time = Date.parse('2026-11-13T12:00:00Z'), calls = 0, fail = false;
const query = new URLSearchParams({ latitude:'10.8231', longitude:'106.6297', timezone:'UTC', timeformat:'unixtime', current:'cloud_cover,rain,showers,weather_code' });
const url = 'http://localhost/api/forecast?' + query;
const proxy = createForecastProxy({ now: () => time, fetcher: async () => {
  calls++;
  await new Promise(resolve => setTimeout(resolve, 5));
  return fail ? new Response('', { status:429, headers:{'Retry-After':'120'} }) : Response.json({ current:{time:time/1000,cloud_cover:80} });
} });
const burst = await Promise.all(Array.from({length:100}, () => proxy.handle(url)));
assert(burst.every(r => r.status === 200)); assert.equal(calls,1);
query.set('latitude','10.8232');
assert.equal((await proxy.handle('http://localhost/api/forecast?' + query)).headers.get('X-Forecast-Cache'),'hit');assert.equal(calls,1);
time += 600001; fail = true;
const stale = await proxy.handle(url);assert.equal((await stale.json())._cache.stale,true);assert.equal(calls,2);
await proxy.handle(url);assert.equal(calls,2);
query.set('latitude','20');
assert.equal((await proxy.handle('http://localhost/api/forecast?' + query)).status,429);assert.equal(calls,2);
time += 1800000;
assert.equal((await proxy.handle(url)).status,429);
assert.equal((await proxy.handle(url + '&apikey=secret')).status,400);
assert.equal((await proxy.handle(url + '&latitude=12')).status,400);
assert.equal((await proxy.handle(url.replace('10.8231','999'))).status,400);
let budgets = 0;
const limited = createForecastProxy({ now:()=>time, perMinute:1, fetcher:async()=>{budgets++;return Response.json({current:{time:time/1000}});} });
await limited.handle(url);
assert.equal((await limited.handle('http://localhost/api/forecast?' + query)).status,429);assert.equal(budgets,1);
console.log('Proxy checks passed: 100 concurrent requests → 1 upstream call, grid reuse, TTL, stale fallback, 429 cooldown, budgets, validation.');

