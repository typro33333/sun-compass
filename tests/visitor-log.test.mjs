import assert from 'node:assert/strict';
import { createVisitorLogger, deviceInfo } from '../lib/visitor-log.mjs';
const seen = new Set(), logs = [], warnings = [];
const redis = { async send(command, args) { assert.equal(command,'EVAL'); const key=args[2]; if(seen.has(key))return 0;seen.add(key);return 1; } };
const first = createVisitorLogger({redis,log:x=>logs.push(JSON.parse(x)),warn:x=>warnings.push(x)});
const request = new Request('https://example.test/',{headers:{'User-Agent':'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) Version/18.0 Mobile Safari/604.1'}});
const cookie = await first.visit(request);
assert.match(cookie,/HttpOnly; SameSite=Lax; Secure/);
assert.equal(logs.length,1);assert.equal(logs[0].device,'mobile');assert.equal(logs[0].os,'iOS');assert.equal(logs[0].browser,'Safari');
assert.equal('ip' in logs[0],false);assert.equal('latitude' in logs[0],false);
const repeat = new Request('https://example.test/',{headers:{cookie:cookie.split(';')[0]}});
const second = createVisitorLogger({redis,log:x=>logs.push(JSON.parse(x))});
assert.equal(await second.visit(repeat),null);assert.equal(logs.length,1);
const invalid = new Request('https://example.test/',{headers:{cookie:'sol_device_id=invalid'}});
assert.match(await first.visit(invalid),/sol_device_id=/);assert.equal(logs.length,2);
const offline = createVisitorLogger({redis:{send:async()=>{throw Error();}},log:x=>logs.push(JSON.parse(x)),warn:x=>warnings.push(x)});
assert.match(await offline.visit(request),/sol_device_id=/);assert.equal(logs.at(-1).storage,'console_only');
await offline.visit(repeat);assert.equal(warnings.length,1);
assert.equal(deviceInfo('Mozilla/5.0 Chrome/120 Edg/120').browser,'Edge');
assert.equal(deviceInfo('Googlebot').device,'bot');
console.log('Visitor log checks passed: new/returning browsers, cross-instance deduplication mock, cookie flags, invalid cookie and Redis failure.');
