const assert = require('node:assert/strict');
const { read, write, migrate } = require('../dist/profile.js');
const profile = { version: 1, kwp: 11, loss: 20, tilt: 15, azimuth: 180, lat: 10.8, lon: 106.6, offset: 7 };
const values = new Map();
const storage = {getItem:key=>values.get(key) ?? null,setItem:(key,value)=>values.set(key,value)};
write(profile,storage); assert.deepEqual(read(storage),profile);
assert.throws(()=>write({...profile,lat:100},storage));
values.set('sol_pv_profile','broken');assert.equal(read(storage),null);
values.clear();
const doc={cookie:'sol_pv_profile='+encodeURIComponent(JSON.stringify(profile))};
assert.deepEqual(migrate(storage,doc),profile);assert.match(doc.cookie,/Max-Age=0/);
write({...profile,kwp:15},storage);
doc.cookie='sol_pv_profile='+encodeURIComponent(JSON.stringify(profile));
assert.equal(migrate(storage,doc).kwp,15,'Local settings take precedence over legacy cookie');
const blocked={getItem(){throw Error('blocked');},setItem(){throw Error('blocked');}};
doc.cookie='sol_pv_profile='+encodeURIComponent(JSON.stringify(profile));
assert.equal(migrate(blocked,doc),null);assert(!doc.cookie.includes('Max-Age=0'),'Do not delete legacy data if migration fails');
assert.equal(read(blocked),null);assert.throws(()=>write(profile,blocked));
console.log('Profile checks passed: localStorage round-trip, validation, cookie migration, precedence and blocked storage.');

const systemProfile={...profile,system:require('../dist/energy.js').defaultSystem()};
write(systemProfile,storage);assert.deepEqual(read(storage),systemProfile);
assert.throws(()=>write({...systemProfile,system:{losses:{},inverter:{}}},storage));
